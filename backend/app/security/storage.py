"""Encrypted-at-rest document storage on the local filesystem.

Files are stored under random keys (never user-supplied names) and encrypted with Fernet
(AES-128-CBC + HMAC-SHA256). Production gaps — key management/rotation via a KMS — are
documented in docs/security.md.
"""
import os
import secrets
from pathlib import Path

from cryptography.fernet import Fernet

from app.config import get_settings


class DocumentStorage:
    def __init__(self, root: str, key: str) -> None:
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)
        self._fernet = Fernet(key.encode())

    def _path(self, storage_key: str) -> Path:
        if not storage_key.isalnum():  # keys are generated by us; refuse anything else
            raise ValueError("invalid storage key")
        return self.root / storage_key[:2] / storage_key

    def put(self, data: bytes) -> str:
        storage_key = secrets.token_hex(24)
        path = self._path(storage_key)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".tmp")
        tmp.write_bytes(self._fernet.encrypt(data))
        os.replace(tmp, path)
        return storage_key

    def get(self, storage_key: str) -> bytes:
        return self._fernet.decrypt(self._path(storage_key).read_bytes())

    def delete(self, storage_key: str) -> None:
        self._path(storage_key).unlink(missing_ok=True)

    def writable(self) -> bool:
        return os.access(self.root, os.W_OK)


_storage: DocumentStorage | None = None


def get_storage() -> DocumentStorage:
    global _storage
    if _storage is None:
        s = get_settings()
        _storage = DocumentStorage(s.storage_dir, s.storage_encryption_key)
    return _storage
